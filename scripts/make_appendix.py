# ---------------------------------------------------------------- helpers
def tex(s):
    return str(s).replace("_", r"\_").replace("%", r"\%")


def pct(x, nd=1):
    return "--" if pd.isna(x) else f"${100 * x:+.{nd}f}\\%$".replace("+0.0\\%", "0.0\\%").replace("-0.0\\%", "0.0\\%")


def pval(p):
    if pd.isna(p):
        return "--"
    if p >= 0.001:
        return f"{p:.3f}"
    m, e = f"{p:.1e}".split("e")
    return f"${m}{{\\times}}10^{{{int(e)}}}$"


def compare(X, Y):
    """Paired graph-level comparison of seed means X, Y (arrays aligned by graph)."""
    X, Y = np.asarray(X, float), np.asarray(Y, float)
    d = (X - Y) / np.maximum(Y, 1)
    tie = (np.abs(X - Y) < 1) | (np.abs(d) <= 0.05)
    nz = d[d != 0]
    p = wilcoxon(nz).pvalue if len(nz) else np.nan
    boot = np.median(d[RNG.integers(0, len(d), (NBOOT, len(d)))], axis=1)
    return dict(n=len(d), w=int((~tie & (d < 0)).sum()), t=int(tie.sum()), l=int((~tie & (d > 0)).sum()),
                med=np.median(d), lo=np.quantile(boot, .025), hi=np.quantile(boot, .975),
                mx=X.mean(), my=Y.mean(), p=p, d=d)


def ci_from_d(d):
    d = np.asarray(d, float)
    boot = np.median(d[RNG.integers(0, len(d), (NBOOT, len(d)))], axis=1)
    return np.quantile(boot, .025), np.quantile(boot, .975)


def row(label, c, extra=""):
    return (f"{label} & {c['w']}/{c['t']}/{c['l']} & {pct(c['med'])} & [{pct(c['lo'])}, {pct(c['hi'])}] & "
            f"{c['mx']:.1f} / {c['my']:.1f} & {pval(c['p'])}{extra} \\\\")


def check(name, c, w, t, l, med, tol=1e-6):
    got = (c["w"], c["t"], c["l"])
    if got != (w, t, l) or abs(c["med"] - med) > tol:
        raise SystemExit(f"MISMATCH {name}: got {got} {c['med']:.4f}, stored {(w, t, l)} {med:.4f}")


def write(name, body):
    with open(os.path.join(TAB, name), "w") as f:
        f.write("% generated by scripts/make_appendix.py -- do not edit by hand\n" + body.strip() + "\n")
    print("wrote", os.path.relpath(os.path.join(TAB, name), ROOT))


